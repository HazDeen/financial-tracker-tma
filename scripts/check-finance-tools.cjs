const ts = require('../frontend/node_modules/typescript');
const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = ts.transpileModule(fs.readFileSync('frontend/src/lib/finance-tools.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const context = { exports: {} }; vm.runInNewContext(source, context);
const { deposit, incomeTax, coupons, multiples, emptyFigures, figureValues, readNumber } = context.exports;
const close = (actual, expected) => assert.ok(Math.abs(actual - expected) < 0.00001, `${actual} != ${expected}`);
close(deposit(100000, 12, 1, false).interest, 1000);
close(deposit(100000, 12, 12, false).interest, 12000);
close(deposit(100000, 12, 12, true).total, 112682.50301319698);
close(deposit(100000, 0, 12, true).interest, 0);
for (const [base, tax] of [[0, 0], [2400000, 312000], [2400001, 312000.15], [5000000, 702000], [20000000, 3402000], [50000000, 9402000], [51000000, 9622000]]) close(incomeTax(base), tax);
close(incomeTax(5000000, true), 702000);
close(incomeTax(20000000, true), 2952000);
close(coupons(1000, 12, 100, 2, 0).net, 10440);
close(coupons(1000, 12, 100, 2, 2394000).tax, 1680); // Half crosses the 2.4m threshold.
close(coupons(1000, 12, 100, 2, 2400000).net, 10200);
close(coupons(1000, 12, 100, 2, 0).perPayment, 6000);
for (const fn of [() => incomeTax(-1), () => incomeTax(Infinity), () => deposit(1, 12, 0, false), () => deposit(1, 12, 1.5, false), () => coupons(1000, 12, 1.5, 2, 0), () => coupons(1000, 12, 10, 0, 0), () => deposit(NaN, 1, 1, false)]) assert.throws(fn);
const figures = { marketCap: '1000', netIncome: '100', revenue: '500', equity: '400', averageEquity: '200', debt: '150', cash: '50', ebitda: '220' };
const ratios = multiples(figures);
close(ratios.pe, 10); close(ratios.ps, 2); close(ratios.pb, 2.5); close(ratios.evEbitda, 5); close(ratios.roe, 50);
assert.equal(multiples(emptyFigures()).pe, null);
assert.equal(multiples({ ...figures, netIncome: '-10' }).pe, null);
close(multiples({ ...figures, netIncome: '-10' }).roe, -5);
assert.equal(multiples({ ...figures, equity: '0', averageEquity: '-10' }).pb, null);
assert.equal(multiples({ ...figures, averageEquity: '-10' }).roe, null);
assert.equal(multiples({ ...figures, debt: '' }).evEbitda, null);
assert.equal(multiples({ ...figures, ebitda: '0' }).evEbitda, null);
assert.throws(() => figureValues({ ...figures, cash: '-1' }));
assert.throws(() => figureValues({ ...figures, netIncome: 'Infinity' }));
assert.throws(() => figureValues({ ...figures, netIncome: 'abc' }));
assert.equal(readNumber('1 234,50'), 1234.5);
assert.equal(readNumber(''), null);
assert.ok(Number.isNaN(readNumber('0x10')));
console.log('Finance checks passed: deposits, capitalization, all tax thresholds, coupon tax crossing, ratios and invalid inputs.');
